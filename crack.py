def discrete_log_prime_pohlig_hellman(g, h, p):
    """Calcula log_g(h) mod p usando Pohlig-Hellman"""
    # Para primos pequeños, usa baby-step giant-step
    n = p - 1  # orden del grupo
    
    # Factorizar n para Pohlig-Hellman
    # Por ahora, solo baby-step giant-step directo
    m_step = int(gmpy2.isqrt(n)) + 1
    
    # Baby steps: calcular g^j para j = 0..m
    table = {}
    val = 1
    for j in range(m_step):
        if val == h:
            return j
        table[val] = j
        val = (val * g) % p
    
    # Giant steps
    factor = pow(g, -m_step, p)
    gamma = h
    for i in range(m_step):
        if gamma in table:
            return i * m_step + table[gamma]
        gamma = (gamma * factor) % p
    
    return None

